const dict: Record<Lang, Record<Key, string>> = { ru, uz };

export function t(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? ru[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const errorText = (lang: Lang, code?: string) => {
  const k = `error.${code}` as Key;
  return code && k in ru ? t(lang, k) : t(lang, 'common.error');
};

export const LANG_COOKIE = 'vitalo_lang';
export const isLang = (v: unknown): v is Lang => v === 'ru' || v === 'uz';

/** «1 товар», «3 товара», «12 товаров»; in Uzbek the noun does not change: «12 ta mahsulot». */
export function productsCount(lang: Lang, n: number): string {
  if (lang === 'uz') return `${n} ta mahsulot`;
  const m10 = n % 10;
  const m100 = n % 100;
  const w = m10 === 1 && m100 !== 11 ? 'товар' : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 'товара' : 'товаров';
  return `${n} ${w}`;
}
