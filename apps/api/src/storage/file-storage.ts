import { Global, Injectable, Module } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { mkdir, rm, writeFile } from 'fs/promises';
import { dirname, join, resolve } from 'path';

/**
 * Where uploaded files (product photos) live. The rest of the code only uses this interface,
 * so moving to S3/MinIO later means adding an S3FileStorage and switching the provider below.
 */
export interface FileStorage {
  /** Stores the file under `key` (e.g. "products/<id>/<uuid>.jpg") and returns its public URL. */
  save(key: string, data: Buffer, contentType: string): Promise<string>;
  /** Deletes a file previously returned by save(); unknown URLs are ignored. */
  remove(url: string): Promise<void>;
}

export const FILE_STORAGE = Symbol('FILE_STORAGE');

export function uploadDir(config: ConfigService): string {
  return resolve(config.get<string>('UPLOAD_DIR') ?? 'uploads');
}

/** Local disk (apps/api/uploads by default), served by the API at /uploads (see app.setup.ts). */
@Injectable()
export class LocalFileStorage implements FileStorage {
  private readonly dir: string;
  private readonly publicBase: string;

  constructor(config: ConfigService) {
    this.dir = uploadDir(config);
    this.publicBase = (config.get<string>('PUBLIC_UPLOADS_URL') ?? '/uploads').replace(/\/$/, '');
  }

  async save(key: string, data: Buffer): Promise<string> {
    const path = this.pathOf(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, data);
    return `${this.publicBase}/${key}`;
  }

  async remove(url: string): Promise<void> {
    if (!url.startsWith(`${this.publicBase}/`)) return;
    await rm(this.pathOf(url.slice(this.publicBase.length + 1)), { force: true });
  }

  /** Keys are generated by our code, but never let one escape the upload folder. */
  private pathOf(key: string): string {
    const path = resolve(join(this.dir, key));
    if (!path.startsWith(this.dir)) throw new Error('Invalid storage key');
    return path;
  }
}

@Global()
@Module({
  providers: [{ provide: FILE_STORAGE, useClass: LocalFileStorage }],
  exports: [FILE_STORAGE],
})
export class StorageModule {}
