-- наши районы и города, которые уже есть: только номер СОАТО (название остаётся нашим)
UPDATE "cities" c SET "soato_code" = s.code
FROM "soato_cities" s JOIN "regions" r ON r."soato_code" = s.region_code
WHERE c."region_id" = r."id" AND c."soato_code" IS NULL
  AND lower(c."name_ru") IN (lower(s.name_ru), lower(COALESCE(s.our_name_ru, s.name_ru)))
