export const dictionaries: Record<Lang, Record<MessageKey, string>> = { ru, uz };

export function translate(lang: Lang, key: MessageKey, params?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? ru[key];
  for (const [k, v] of Object.entries(params ?? {})) text = text.split(`{${k}}`).join(String(v));
  return text;
}

/** Localized message for an API error code, or the generic error text. */
export function errorText(lang: Lang, code: string | undefined): string {
  const key = `error.${code}` as MessageKey;
  return code && key in ru ? translate(lang, key) : translate(lang, 'common.error');
}

/** Russian plural form: 1 товар, 3 товара, 5 товаров, 21 товар, 11 товаров. */
export function pluralForm(n: number): 'one' | 'few' | 'many' {
  const d = n % 10;
  const h = n % 100;
  if (d === 1 && h !== 11) return 'one';
  if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return 'few';
  return 'many';
}

/** Order status shown to the customer; "Я оплатил(а)" pressed but not confirmed yet = checking. */
/** Status for colour and icon: "Я оплатил(а)" pressed but not confirmed yet = checking. */
export const shownStatus = (s: OrderStatus, paymentReported = false): OrderStatus | 'checking' =>
  paymentReported && (s === 'awaiting_payment' || s === 'new') ? 'checking' : s;

export const statusKey = (s: OrderStatus, paymentReported = false) => `status.${shownStatus(s, paymentReported)}` as MessageKey;

/**
 * The one status text of an order for the customer (D-53): «Оплата при получении» waits for the manager
 * («Ожидает подтверждения»), then is «Подтверждён» until it goes to the warehouse — never «Оплачен».
 */
export const orderStatusKey = (s: OrderStatus, opts: { reported?: boolean; cod?: boolean } = {}): MessageKey => {
  if (opts.cod && (s === 'new' || s === 'awaiting_payment')) return 'status.codWaiting';
  if (opts.cod && s === 'paid') return 'status.codConfirmed';
  return statusKey(s, opts.reported);
};

interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: MessageKey, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ lang, setLang, children }: { lang: Lang; setLang: (l: Lang) => void; children: ReactNode }) {
  const t = (key: MessageKey, params?: Record<string, string | number>) => translate(lang, key, params);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n outside I18nProvider');
  return ctx;
}
